// Activity: Print the multiplication table of 9 from 1 to 10
// Module 2: OOP. Basic Concepts I (Java Introduction)
// ==============================================================================

public class MultiplicationTable {
    public static void main(String[] args) {
        // Counter-driven loop from 1 to 10 to output each multiplication sequence
        for (int i = 1; i <= 10; i++) {
            System.out.println(i + " X 9 = " + (i * 9));
        }
    }
}
